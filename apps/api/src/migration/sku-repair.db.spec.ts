import 'reflect-metadata';
import { randomBytes } from 'node:crypto';
import { DataSource } from 'typeorm';
import { buildDataSourceOptions } from '../database/data-source';
import { Company, Department, FlowDefinition, Position, PositionPermission, ResourceRecord, User, UserPermissionOverride } from '../entities';
import { buildServices } from '../test-support';
import { LegacyArchive } from './protocol';
import { runSkuRepair } from './sku-repair';
import { configureSkuWorkflow } from './sku-workflow';

const d=process.env.RESOURCE_DB_TEST==='1'?describe:describe.skip;
d('SKU专项修复：回滚、并发及人工修改保护',()=>{
  let ds:DataSource,s:ReturnType<typeof buildServices>['resources'];
  beforeAll(async()=>{ds=await new DataSource({...buildDataSourceOptions({...process.env,DB_NAME:process.env.TEST_DB_NAME??'kudesi_oa_test'}),migrationsRun:true}).initialize();s=buildServices(ds).resources;});
  afterAll(async()=>{await ds?.destroy();});
  it('空跑确实回滚；报告过期拒绝；正式执行保留人工改过的字段',async()=>{
    const token=randomBytes(5).toString('hex'),c=await ds.manager.save(Company,ds.manager.create(Company,{code:'repair'+token,name:'修复测试',status:'active'}));
    const u=await ds.manager.save(User,ds.manager.create(User,{companyId:c.id,account:'repair'+token,name:'管理员',passwordHash:'x',status:'active',isCompanyAdmin:true,mustChangePassword:false}));
    const actor={id:u.id,companyId:c.id,name:u.name,permissions:{isCompanyAdmin:true,allow:[],deny:[]}};
    const cat=await s.create(actor,'finance-categories',{archiveType:'package',name:'包装'});
    const p=await s.create(actor,'finance-products',{archiveType:'package',categoryId:cat.id,name:'纸盒',capacities:'1KG',weightG:25,purchasePrice:100,freight:1,handlingFee:1});
    await ds.query("INSERT INTO legacy_import_links(source_system,source_company_id,company_id,source_key,target_type,target_id,source_hash) VALUES('legacy-oa',3,?,'finance-products:old-p','finance-products',?,?)",[c.id,p.id,'0'.repeat(64)]);
    await ds.query("UPDATE resource_records SET data=JSON_SET(data,'$.weightG',1000) WHERE id=? AND company_id=?",[p.id,c.id]);
    const source:LegacyArchive={company:{id:3,name:c.name},departments:[],positions:[],employees:[],employeePositions:[],positionPermissions:[],records:[{id:'old-p',type:'finance-products',data:{weightG:25,purchaseSpec:'个'}}],exclusions:[],loadFile:async()=>{throw Error('no files');}};
    const opts={companyId:c.id,actorId:u.id,expectedName:c.name,apply:false};
    const dry=await runSkuRepair(ds,s,source,opts);
    expect(dry.patches).toHaveLength(1);
    expect((await ds.manager.findOneByOrFail(ResourceRecord,{id:p.id})).data.weightG).toBe(1000);
    await s.update(actor,'finance-products',p.id,{weightG:37},'财务核对后调整');
    await expect(runSkuRepair(ds,s,source,{...opts,apply:true,expectedPlan:dry})).rejects.toThrow(/空跑不一致/);
    const fresh=await runSkuRepair(ds,s,source,opts);
    expect(fresh.conflicts.some(x=>x.field==='weightG')).toBe(true);
    await runSkuRepair(ds,s,source,{...opts,apply:true,expectedPlan:fresh});
    const after=await ds.manager.findOneByOrFail(ResourceRecord,{id:p.id});
    expect(after.data.weightG).toBe(37);expect(after.data.purchaseSpec).toBe('个');

    const brand=await s.create(actor,'finance-brands',{name:'演练品牌'}),madeCat=await s.create(actor,'finance-categories',{archiveType:'self_made',name:'自产'}),owner=await s.create(actor,'finance-products',{archiveType:'self_made',name:'自产礼盒',brandId:brand.id,categoryId:madeCat.id});
    const bom=await s.create(actor,'finance-product-boms',{productId:owner.id,componentId:p.id,qty:1});
    for(const [key,type,id] of [['finance-products:owner','finance-products',owner.id],['finance-product-boms:old-line','finance-product-boms',bom.id]] as const)await ds.query("INSERT INTO legacy_import_links(source_system,source_company_id,company_id,source_key,target_type,target_id,source_hash) VALUES('legacy-oa',3,?,?,?,?,?)",[c.id,key,type,id,'0'.repeat(64)]);
    source.records.push({id:'new-line',type:'finance-product-boms',data:{productId:{legacyRef:{type:'finance-products',id:'owner'}},componentId:{legacyRef:{type:'finance-products',id:'old-p'}},qty:1,lossPercent:0}});
    const relink=await runSkuRepair(ds,s,source,opts);
    expect(relink.relinks).toHaveLength(1);expect(relink.additions).toHaveLength(0);
    await runSkuRepair(ds,s,source,{...opts,apply:true,expectedPlan:relink});
    expect(await ds.manager.count(ResourceRecord,{where:{companyId:c.id,type:'finance-product-boms'}})).toBe(1);
    const [mapped]=await ds.query("SELECT target_id FROM legacy_import_links WHERE company_id=? AND source_key='finance-product-boms:new-line'",[c.id]);expect(Number(mapped.target_id)).toBe(bom.id);

    const dept=await ds.manager.save(Department,ds.manager.create(Department,{companyId:c.id,name:'仓库',status:'active'})),position=await ds.manager.save(Position,ds.manager.create(Position,{companyId:c.id,name:'财务',status:'active'}));
    await ds.manager.update(User,{id:u.id,companyId:c.id},{departmentId:dept.id});
    const finance=await ds.manager.save(User,ds.manager.create(User,{companyId:c.id,account:'fin'+token,name:'财务',positionId:position.id,passwordHash:'x',status:'active',isCompanyAdmin:false,mustChangePassword:false}));
    const baseFlowOpts={...opts,warehouseDepartmentId:dept.id,financePositionId:position.id};
    await expect(configureSkuWorkflow(ds,s,baseFlowOpts)).rejects.toThrow(/缺少成本查看/);
    const flowOpts={...baseFlowOpts,grantRequiredFinancePermissions:true};
    const deny=await ds.manager.save(UserPermissionOverride,ds.manager.create(UserPermissionOverride,{userId:finance.id,permission:'product.cost.view',effect:'deny'}));
    await expect(configureSkuWorkflow(ds,s,flowOpts)).rejects.toThrow(/明确禁止/);
    expect(await ds.manager.count(PositionPermission,{where:{positionId:position.id}})).toBe(0);
    await ds.manager.delete(UserPermissionOverride,{id:deny.id});
    const workflow=await configureSkuWorkflow(ds,s,flowOpts);
    expect(workflow.grants).toHaveLength(3);
    expect(await ds.manager.count(PositionPermission,{where:{positionId:position.id}})).toBe(0);
    expect(await ds.manager.count(FlowDefinition,{where:{companyId:c.id}})).toBe(0);
    await configureSkuWorkflow(ds,s,{...flowOpts,apply:true,expected:workflow});
    expect(await ds.manager.count(PositionPermission,{where:{positionId:position.id}})).toBe(3);
    expect(await ds.manager.count(FlowDefinition,{where:{companyId:c.id,status:'active'}})).toBe(1);
    await expect(configureSkuWorkflow(ds,s,flowOpts)).rejects.toThrow(/已有人工配置/);
  });
});
