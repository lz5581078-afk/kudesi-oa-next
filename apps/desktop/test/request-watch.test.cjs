const {test}=require('node:test'),assert=require('node:assert/strict');
const {createRequestWatch}=require('../src/request-watch.cjs');
test('request proof distinguishes completion, failure and other clients without inspecting credentials or data',()=>{
 const listeners={},session={webRequest:{onBeforeRequest:cb=>listeners.before=cb,onCompleted:cb=>listeners.done=cb,onErrorOccurred:cb=>listeners.error=cb}};
 const controls=createRequestWatch(session),a=controls.forContents(1),b=controls.forContents(2);a.arm();b.arm();
 const request=(id,webContentsId)=>{const d={id,webContentsId,resourceType:'xhr',url:'https://erp321.com/example'};for(const key of ['requestHeaders','uploadData'])Object.defineProperty(d,key,{get:()=>{throw new Error('Credentials and data must never be read');}});listeners.before(d,()=>{});};
 request(10,1);request(11,2);assert.equal(a.state().pending,1);assert.equal(b.state().pending,1);
 listeners.done({id:10,statusCode:200});assert.equal(a.state().completed,1);assert.equal(a.state().failed,0);assert.equal(b.state().pending,1);
 listeners.error({id:11});assert.equal(b.state().failed,1);assert.equal(b.state().pending,0);
 a.arm();request(12,1);listeners.done({id:12,statusCode:503});assert.equal(a.state().failed,1);
 a.stop();request(13,1);assert.equal(a.state(),null);
});
test('current list proof ignores auxiliary failures and accepts a successful replacement request',()=>{
 const {createListRequestTracker}=require('../src/request-watch.cjs');
 const watch=createListRequestTracker(),url='https://innerapi.scm121.com/api/inner/after-sale/page/list';
 watch.arm('current');
 watch.start(1,'https://sc.scm121.com/api/company/after-sale/ipc/has-video','POST','fetch');
 watch.start(2,url,'GET','xhr');
 watch.start(3,url,'POST','fetch');
 watch.start(4,url,'POST','fetch');
 watch.finish(1,true);
 watch.finish(4,false);
 watch.finish(3,true);
 assert.equal(watch.state().started,2);
 assert.equal(watch.state().pending,0);
 assert.equal(watch.state().completed,2);
 assert.equal(watch.state().failed,0);
 watch.start(5,url,'POST','fetch');
 watch.finish(5,true);
 assert.equal(watch.state().failed,1);
});
