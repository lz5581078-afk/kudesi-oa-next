import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, expect, it, vi } from 'vitest';
import { api } from '../../api/client';
import { CompanyProductsPage } from './CompanyProductsPage';
vi.mock('../../api/client', () => ({ api: vi.fn(), ApiError: class extends Error {} }));
vi.mock('../../auth/AuthContext', () => ({ useAuth: () => ({user:{id:1,companyId:1,permissions:{isCompanyAdmin:false}},can:()=>true}) }));
vi.mock('../flow/SkuApplicationCenter', () => ({SkuApplicationCenter:({initialQuery}:{initialQuery:string})=><div role="dialog">{initialQuery}</div>}));
afterEach(()=>{cleanup();vi.resetAllMocks();});
it('同一档案的马甲独立卡片，详情及申请保留马甲且不提供原图链接', async()=>{
  const common={id:1,code:'A',category:'种子',specification:'1 千克',stock:8,stockUnit:'千克',stockBalances:[{unit:'千克',qty:8}],owners:[],tags:[],priceRestricted:false};
  const photo={url:'https://example.invalid/original.jpg',name:'产品图片'};
  const one={...common,name:'马甲甲',alias:'马甲甲',imagePosition:'0% 0%',photo};
  const two={...common,name:'马甲乙',alias:'马甲乙',imagePosition:'80% 80%',photo};
  vi.mocked(api).mockImplementation(async(path)=> path.includes('/1?')?{...two,photos:[photo],weightG:1000}:{items:[one,two],total:2,page:1,pageSize:24,counts:{10:2},categories:[{id:10,name:'种子',parentId:null}]} as never);
  render(<MemoryRouter><CompanyProductsPage/></MemoryRouter>);
  await screen.findByText('马甲甲');
  const cards=screen.getAllByRole('link').filter(link=>link.classList.contains('company-product-card'));
  expect(cards).toHaveLength(2);
  expect(cards[0].getAttribute('href')).not.toBe(cards[1].getAttribute('href'));
  const pictures=screen.getAllByRole('img') as HTMLImageElement[];
  expect(pictures.every(image => !image.style.transform && !image.style.transformOrigin)).toBe(true);
  fireEvent.click(cards[1]);
  await screen.findByRole('heading',{name:'马甲乙'});
  expect(api).toHaveBeenCalledWith(`/workspace/company-products/1?${new URLSearchParams({alias:'马甲乙'})}`);
  expect(screen.queryByRole('link',{name:'打开原图'})).toBeNull();
  expect(screen.getByRole('img').closest('a')).toBeNull();
  expect(screen.getByRole('img').style.transformOrigin).toBe('');
  fireEvent.click(screen.getByRole('button',{name:/申请 SKU/}));
  expect((await screen.findByRole('dialog')).textContent).toBe('马甲乙');
});
